#!/usr/bin/env python3
"""Auto-generate docs/ARCHITECTURE.md based on flywheel/config.json and repo structure.

Run from anywhere: python3 flywheel/dashboard/gen_architecture.py [target-dir]
"""
import json
import os
import sys

def main():
    target_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    config_path = os.path.join(target_dir, "flywheel", "config.json")
    if not os.path.isfile(config_path):
        print(f"Error: config.json not found at {config_path}")
        sys.exit(1)
        
    try:
        with open(config_path, "r", encoding="utf-8") as f:
            config = json.load(f)
    except Exception as e:
        print(f"Error reading config.json: {e}")
        sys.exit(1)
        
    project_name = config.get("project_name", "flywheel")
    
    # Read models per tier from config
    tiers = config.get("tiers", {})
    tier_info = {}
    for name, tdata in tiers.items():
        role = tdata.get("role", "")
        adapters = tdata.get("adapters", {})
        adapter_names = ["antigravity", "claude-code", "codex", "opencode"]
        model = "Unknown"
        for a in adapter_names:
            if a in adapters:
                model = adapters[a].get("model", "Unknown")
                break
        tier_info[name] = {"role": role, "model": model}
        
    doc_content = f"""# Flywheel Architecture & Tech-Stack

This document is automatically generated by `gen_architecture.py`. It describes the layout, components, and communication pathways of the **{project_name}** framework instance.

## Tech-Stack Overview
- **Core Orchestrator**: Multi-tier agentic wrapper supporting Claude Code, Codex, and Google Antigravity.
- **Automation Engine**: POSIX Bash shells + Python 3 / Node.js utility scripts.
- **State Store**: Flat JSON-based ledger files (schema-validated).
- **Dashboard**: Pure HTML5/CSS3 single-page web dashboard with dark-mode support and client-side reactive rendering.

## Component Architecture

```mermaid
flowchart TD
    coord["Coordinator<br>(Main Session)"]
    architect["Architect Tier<br>(architect)"]
    strategist["Strategist Tier<br>(researcher)"]
    engineer["Engineer Tier<br>(engineer)"]
    utility["Utility Tier<br>(utility)"]
    verifier["Verifier Tier<br>(verifier)"]
    auditor["Auditor Tier<br>(plan-auditor)"]

    check_sh["check.sh<br>(Consistency Check)"]
    wrapup_sh["wrapup.sh<br>(Session Wrapup)"]
    sync_py["sync.py<br>(Config Sync)"]
    compact_py["compact.py<br>(Ledger Compactor)"]
    resolve_spawn_py["resolve-spawn.py<br>(Spawn Hook Handler)"]

    state_projects["state/projects.json"]
    state_issues["state/issues.json"]
    state_decisions["state/decisions.json"]
    state_activity["state/activity.json"]
    state_spawns["state/spawns.json"]

    build_py["build.py / build.mjs<br>(Dashboard Builder)"]
    dashboard["dashboard.html<br>(CEO Dashboard)"]

    coord -->|Delegates to| architect
    coord -->|Delegates to| strategist
    coord -->|Delegates to| engineer
    coord -->|Delegates to| utility
    coord -->|Delegates to| verifier
    coord -->|Delegates to| auditor

    coord -->|Runs| check_sh
    coord -->|Runs| wrapup_sh
    
    wrapup_sh -->|Runs| check_sh
    wrapup_sh -->|Runs| build_py
    wrapup_sh -->|Commits| state_projects
    wrapup_sh -->|Commits| state_issues
    wrapup_sh -->|Commits| state_decisions
    wrapup_sh -->|Commits| state_activity
    wrapup_sh -->|Commits| state_spawns

    build_py -->|Reads| state_projects
    build_py -->|Reads| state_issues
    build_py -->|Reads| state_decisions
    build_py -->|Reads| state_activity
    build_py -->|Reads| state_spawns
    build_py -->|Generates| dashboard

    click coord "../flywheel/INDEX.md" "View framework index"
    click check_sh "../flywheel/check.sh" "View check.sh script"
    click wrapup_sh "../flywheel/wrapup.sh" "View wrapup.sh script"
    click sync_py "../flywheel/sync.py" "View sync.py script"
    click compact_py "../flywheel/compact.py" "View compact.py script"
    click resolve_spawn_py "../flywheel/resolve-spawn.py" "View resolve-spawn.py script"
    click state_projects "../flywheel/state/projects.json" "View projects ledger"
    click state_issues "../flywheel/state/issues.json" "View issues ledger"
    click state_decisions "../flywheel/state/decisions.json" "View decisions ledger"
    click state_activity "../flywheel/state/activity.json" "View activity ledger"
    click state_spawns "../flywheel/state/spawns.json" "View spawns ledger"
    click dashboard "../flywheel/dashboard/dashboard.html" "View compiled dashboard"
```

## Active Tiers & Models
- **architect**: {tier_info.get('architect', {}).get('role', '')} (Model: `{tier_info.get('architect', {}).get('model', '')}`)
- **strategist**: {tier_info.get('strategist', {}).get('role', '')} (Model: `{tier_info.get('strategist', {}).get('model', '')}`)
- **engineer**: {tier_info.get('engineer', {}).get('role', '')} (Model: `{tier_info.get('engineer', {}).get('model', '')}`)
- **utility**: {tier_info.get('utility', {}).get('role', '')} (Model: `{tier_info.get('utility', {}).get('model', '')}`)
- **verifier**: {tier_info.get('verifier', {}).get('role', '')} (Model: `{tier_info.get('verifier', {}).get('model', '')}`)
- **auditor**: {tier_info.get('auditor', {}).get('role', '')} (Model: `{tier_info.get('auditor', {}).get('model', '')}`)
"""
    output_docs_dir = os.path.join(target_dir, "docs")
    os.makedirs(output_docs_dir, exist_ok=True)
    output_path = os.path.join(output_docs_dir, "ARCHITECTURE.md")
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(doc_content)
    print(f"wrote {output_path}")

if __name__ == "__main__":
    main()
